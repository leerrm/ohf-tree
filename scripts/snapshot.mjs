/**
 * Captures every source declared in src/content/projects/*.yaml into a module
 * bundled with the SSR function, so a page always has known-good items to fall
 * back on when a live fetch is slow or down.
 *
 * Best effort by design: a failing feed warns and is simply absent from the
 * snapshot. It must never fail a deploy — that would make a third-party outage
 * our outage. The weekly feed-health workflow is what complains loudly.
 */
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';
import { parseFeed } from '../src/feeds/parse-feed.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const projectsDir = join(root, 'src/content/projects');
const outFile = join(root, 'src/generated/feed-snapshot.ts');
const TIMEOUT_MS = 10_000;
/** --strict turns a dead feed into a failure; used by the weekly health check. */
const STRICT = process.argv.includes('--strict');

async function fetchText(url) {
  const response = await fetch(url, {
    signal: AbortSignal.timeout(TIMEOUT_MS),
    headers: { 'user-agent': 'ohf-tree snapshot (+https://www.openhomefoundation.org)' },
  });
  if (!response.ok) throw new Error(`responded ${response.status}`);
  return response.text();
}

async function capture(config) {
  if (config.type === 'rss' || config.type === 'mastodon') {
    return parseFeed(await fetchText(config.url));
  }

  if (config.type === 'github-releases') {
    const headers = { 'user-agent': 'ohf-tree snapshot' };
    if (process.env.GITHUB_TOKEN) headers.authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
    const response = await fetch(
      `https://api.github.com/repos/${config.repo}/releases?per_page=10`,
      { signal: AbortSignal.timeout(TIMEOUT_MS), headers },
    );
    if (!response.ok) throw new Error(`responded ${response.status}`);
    const releases = await response.json();
    return releases
      .filter((r) => !r.draft && (config.includePrereleases || !r.prerelease))
      .map((r) => ({
        title: r.name?.trim() || r.tag_name,
        url: r.html_url,
        date: r.published_at ? new Date(r.published_at) : undefined,
      }));
  }

  // Pins need no snapshot — they are already in the bundle.
  return [];
}

const snapshot = {};
let failures = 0;

const files = (await readdir(projectsDir)).filter((file) => file.endsWith('.yaml'));

for (const file of files) {
  const project = file.replace(/\.yaml$/, '');
  const config = parse(await readFile(join(projectsDir, file), 'utf8')) ?? {};

  for (const [name, source] of Object.entries(config.sources ?? {})) {
    if (source?.type === 'pinned') continue;
    try {
      const items = await capture(source);
      if (items.length > 0) {
        snapshot[`${project}:${name}`] = items.slice(0, 10).map((item) => ({
          title: item.title,
          url: item.url,
          date: item.date instanceof Date ? item.date.toISOString() : item.date,
          excerpt: item.excerpt,
        }));
      }
      console.log(`  ok   ${project}:${name} (${items.length})`);
    } catch (error) {
      failures += 1;
      console.warn(`  warn ${project}:${name} — ${error.message}`);
    }
  }
}

await mkdir(dirname(outFile), { recursive: true });
await writeFile(
  outFile,
  `// Generated by scripts/snapshot.mjs — do not edit.\n` +
    `export const snapshot = ${JSON.stringify(snapshot, null, 2)} as const;\n`,
);

console.log(
  `snapshot: ${Object.keys(snapshot).length} source(s) captured` +
    (failures ? `, ${failures} unavailable` : ''),
);

if (STRICT && failures > 0) {
  console.error(`${failures} source(s) could not be reached.`);
  process.exit(1);
}
